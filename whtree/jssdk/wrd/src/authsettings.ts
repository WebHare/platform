/** This library implements the AuthenticationSettings type */

import { decodeHSON, defaultDateTime, encodeHSON, HareScriptType, setHareScriptType } from "@webhare/hscompat";
import { createWebHarePasswordHash, isPasswordStillSecure, verifyWebHarePasswordHash } from "@webhare/hscompat/src/passwords";

interface HSONAuthenticationSettings {
  version: number;
  passwords?: Array<{ passwordhash: string; validfrom: Date }>;
  totp?: {
    url: string;
    backupcodes?: Array<{
      code: string;
      used?: Date;
    }>;
    locked?: Date;
  };
}

/** Exported (JSON/YAML-safe) version of AuthenticationSettings. Dates are ISO 8601 strings */
export interface ExportedAuthenticationSettings {
  version: 1;
  passwords: Array<{ hash: string; validFrom: string | null }>;
  totp: {
    url: string;
    backupCodes: Array<{ code: string; used: string | null }>;
    locked: string | null;
  } | null;
}

/** Convert HareScript's default datetime to null */
function hsDateToNull(date: Date | null | undefined): Date | null {
  return !date || date.getTime() <= defaultDateTime.getTime() ? null : date;
}

function exportDate(date: Date | null): string | null {
  return date ? date.toISOString() : null;
}

function importDate(date: unknown, what: string): Date | null {
  if (date === null || date === undefined || date === "")
    return null;
  const parsed = date instanceof Date ? date : typeof date === "string" ? new Date(date) : null;
  if (!parsed || isNaN(parsed.getTime()))
    throw new Error(`Invalid date for ${what}: ${JSON.stringify(date)}`);
  return parsed;
}

export class AuthenticationSettings {
  #passwords: Array<{ hash: string; validFrom: Date | null }> = [];
  #totp: {
    url: string;
    backupCodes: Array<{ code: string; used: Date | null }>;
    locked: Date | null;
  } | null = null;

  static fromPasswordHash(hash: string): AuthenticationSettings {
    const auth = new AuthenticationSettings;
    if (hash) //shouldn't set a validity date, the passord will look too recently changed and interfere with password resets
      auth.#passwords.push({ hash, validFrom: null });
    return auth;
  }

  static fromHSON(hson: string): AuthenticationSettings {
    const obj = decodeHSON(hson) as unknown as HSONAuthenticationSettings;
    if (typeof obj !== "object")
      throw new Error(`Expected a HSON encoded record, got '${typeof obj}'`);
    if (!obj || !("version" in obj))
      throw new Error("Missing version field");
    if (obj.version !== 1)
      throw new Error(`Unsupported authentication settings version ${obj.version}`);

    const auth = new AuthenticationSettings;
    if (Array.isArray(obj.passwords))
      for (const pwd of (obj.passwords ?? [])) {
        if (!pwd || !pwd.passwordhash || !pwd.validfrom)
          throw new Error("Invalid password record");
        auth.#passwords.push({ hash: pwd.passwordhash, validFrom: hsDateToNull(pwd.validfrom) });
      }

    if (obj.totp) {
      auth.#totp = {
        url: obj.totp.url,
        backupCodes: (obj.totp.backupcodes ?? []).map(_ => ({ code: _.code, used: hsDateToNull(_.used) })),
        locked: hsDateToNull(obj.totp.locked)
      };
    }
    return auth;
  }

  toHSON() {
    const passwords = this.#passwords.map(_ => ({ passwordhash: _.hash, validfrom: _.validFrom ?? defaultDateTime }));
    setHareScriptType(passwords, HareScriptType.RecordArray);

    return encodeHSON({
      version: 1,
      passwords,
      totp: this.#totp ? {
        url: this.#totp.url,
        backupcodes: setHareScriptType(this.#totp.backupCodes.map(_ => ({ code: _.code, used: _.used ?? defaultDateTime })), HareScriptType.RecordArray),
        locked: this.#totp.locked ?? defaultDateTime
      } : null
    });
  }

  /** Import authentication settings from their exported form (as generated by export())
   * @param data - Exported authentication settings
   */
  static import(data: ExportedAuthenticationSettings): AuthenticationSettings {
    if (!data || typeof data !== "object" || Array.isArray(data))
      throw new Error(`Expected an object with exported authentication settings, got ${JSON.stringify(data)}`);
    if (data.version !== 1)
      throw new Error(`Unsupported authentication settings version ${JSON.stringify(data.version)}`);
    if (data.passwords !== undefined && !Array.isArray(data.passwords))
      throw new Error("Authentication settings 'passwords' must be an array");

    const auth = new AuthenticationSettings;
    for (const [idx, pwd] of (data.passwords ?? []).entries()) {
      if (!pwd || typeof pwd.hash !== "string" || !pwd.hash)
        throw new Error(`Invalid password record #${idx}: missing hash`);
      auth.#passwords.push({ hash: pwd.hash, validFrom: importDate(pwd.validFrom, `passwords[${idx}].validFrom`) });
    }

    if (data.totp) {
      if (typeof data.totp.url !== "string" || !data.totp.url)
        throw new Error("Authentication settings 'totp' must have a url");
      if (data.totp.backupCodes !== undefined && !Array.isArray(data.totp.backupCodes))
        throw new Error("Authentication settings 'totp.backupCodes' must be an array");

      auth.#totp = {
        url: data.totp.url,
        backupCodes: (data.totp.backupCodes ?? []).map((bc, idx) => {
          if (!bc || typeof bc.code !== "string" || !bc.code)
            throw new Error(`Invalid backup code record #${idx}: missing code`);
          return { code: bc.code, used: importDate(bc.used, `totp.backupCodes[${idx}].used`) };
        }),
        locked: importDate(data.totp.locked, "totp.locked")
      };
    }
    return auth;
  }

  /** Export authentication settings to a JSON/YAML-safe form. Note that this includes password hashes and the TOTP secret */
  export(): ExportedAuthenticationSettings {
    return {
      version: 1,
      passwords: this.#passwords.map(_ => ({ hash: _.hash, validFrom: exportDate(_.validFrom) })),
      totp: this.#totp ? {
        url: this.#totp.url,
        backupCodes: this.#totp.backupCodes.map(_ => ({ code: _.code, used: exportDate(_.used) })),
        locked: exportDate(this.#totp.locked)
      } : null
    };
  }

  hasTOTP(): boolean {
    return Boolean(this.#totp);
  }

  getLastPasswordChange(): Temporal.Instant | null {
    return this.#passwords.at(-1)?.validFrom?.toTemporalInstant() ?? null;
  }

  isPasswordStillSecure(): boolean {
    return this.#passwords.length === 0 || isPasswordStillSecure(this.#passwords.at(-1)!.hash);
  }

  getNumPasswords(): number {
    return this.#passwords.length;
  }

  //TODO when to clear password? probably needs to be a WRD schema setting enforced on updateEntity
  /** Update the password in this setting
   * @param password - The new password
   * @param options - Options for updating the password
   * @param options.algorithm - The hash algorithm to use. If not set, use best known method (may change in future versions)
   * @param options.inPlace - Update the last password in place (if it exists), otherwise add to the list. Used to upgrade passwords to a new algorithm without changing the password history and resetting the password age
  */
  async updatePassword(password: string, options?: { algorithm?: "PLAIN" | "WHBF"; inPlace?: boolean }): Promise<void> {
    if (!password)
      throw new Error("Password cannot be empty");

    let hash = '';
    const alg = options?.algorithm ?? "WHBF"; //default to WHBF, which is the best known method
    if (alg === "PLAIN")
      hash = 'PLAIN:' + password;
    else if (alg === "WHBF")
      hash = await createWebHarePasswordHash(password);
    else
      throw new Error(`Unsupported password hash algorithm '${alg}'`);

    if (options?.inPlace && this.#passwords.length > 0)
      this.#passwords.at(-1)!.hash = hash;
    else
      this.#passwords.push({ hash, validFrom: new Date });
  }

  async verifyPassword(password: string): Promise<boolean> {
    if (!password || !this.#passwords.length)
      return false;

    const tryHash = this.#passwords[this.#passwords.length - 1].hash;
    if (tryHash.startsWith("PLAIN:"))
      return password === tryHash.substring(6);

    return await verifyWebHarePasswordHash(password, tryHash);
  }

  async isUsedSince(password: string, cutoff: Temporal.Instant): Promise<boolean> {
    for (let i = this.#passwords.length - 1; i >= 0; i--) {
      const tryHash = this.#passwords[i].hash;
      if (tryHash.startsWith("PLAIN:")) {
        if (password === tryHash.substring(6))
          return true;
      } else if (await verifyWebHarePasswordHash(password, tryHash))
        return true;
      const vf = this.#passwords[i].validFrom;
      if (!vf || vf.getTime() <= cutoff.epochMilliseconds)
        break;
    }
    return false;
  }
}
