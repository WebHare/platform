/* Exposes the AI skills of webhare.dev over MCP. Skills are read either from the locally installed webhare_dev module
   (content/ai/skills/<skill>/SKILL.md) or from the webhare.dev site (<site>/ai/index.json), depending on the
   devkit:integrations.use_checkedout_site and devkit:integrations.webhare_dev_site registry keys */

import { backendConfig, getRegistryKeyEventMasks, readRegistryKey, subscribe } from "@webhare/services";
import { YAML } from "@webhare/deps";
import { existsSync, statSync, watch } from "node:fs";
import { readdir, readFile } from "node:fs/promises";
import { join, relative, sep } from "node:path";

export interface SkillInfo {
  /** Skill name (from frontmatter, falls back to directory name) */
  name: string;
  /** Skill description from the frontmatter */
  description: string;
  /** All files in the skill directory, relative to that directory ('/' separated). Includes SKILL.md */
  files: string[];
}

/** A place we get skills from */
export interface SkillSource {
  /** Explanation of where the skills come from, for the server instructions */
  describe(): string;
  /** Short description for logging */
  location: string;
  listSkills(): Promise<SkillInfo[]>;
  /** Read a file of a skill. Only called for files listed in SkillInfo.files */
  readSkillFile(skill: string, file: string): Promise<string>;
  /** Start monitoring for changes, invoking the callback with the names of changed files ("<skill>/<file>") if known
      @returns A function to stop monitoring */
  watch(onChange: (changedFiles: string[]) => void): () => void;
}

/** Format of <site>/ai/index.json, as generated by webhare_dev's update-from-github task */
interface SkillIndex {
  version: 1;
  commit: string;
  skills: Array<{ name: string; description: string; path: string; files: string[] }>;
}

const skillUriPrefix = "skill://";
const remoteRefreshInterval = 15 * 60 * 1000;

/** Split a markdown file into its YAML frontmatter and body */
function parseFrontmatter(text: string): { meta: Record<string, unknown>; body: string } {
  const match = text.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!match)
    return { meta: {}, body: text };
  let meta: Record<string, unknown> = {};
  try {
    const parsed = YAML.parse(match[1]);
    if (parsed && typeof parsed === "object")
      meta = parsed;
  } catch {
    //ignore broken frontmatter, we'll fall back to defaults
  }
  return { meta, body: text.slice(match[0].length) };
}

/** Skills from the locally installed webhare_dev module */
class LocalSkillSource implements SkillSource {
  readonly skillsRoot: string;

  constructor(skillsRoot: string) {
    this.skillsRoot = skillsRoot;
  }

  get location() {
    return this.skillsRoot;
  }

  describe() {
    return `The skills are read from the local webhare_dev checkout on disk at ${this.skillsRoot} - each skill is a subdirectory containing a SKILL.md file (with 'name' and 'description' frontmatter) and optional supporting files. If the user asks you to create, update or fix a skill, edit the files in that directory directly. Changes are picked up automatically.`;
  }

  /** Map skill names to their directories */
  private async getSkillDirs(): Promise<Map<string, { dir: string; description: string }>> {
    const result = new Map<string, { dir: string; description: string }>();
    for (const entry of await readdir(this.skillsRoot, { withFileTypes: true })) {
      if (!entry.isDirectory() || entry.name.startsWith("."))
        continue;
      const dir = join(this.skillsRoot, entry.name);
      const skillfile = join(dir, "SKILL.md");
      if (!existsSync(skillfile))
        continue;

      const { meta } = parseFrontmatter(await readFile(skillfile, "utf8"));
      result.set(typeof meta.name === "string" && meta.name ? meta.name : entry.name, {
        dir,
        description: typeof meta.description === "string" ? meta.description : ""
      });
    }
    return result;
  }

  async listSkills(): Promise<SkillInfo[]> {
    const skills: SkillInfo[] = [];
    for (const [name, { dir, description }] of await this.getSkillDirs()) {
      const files = (await readdir(dir, { withFileTypes: true, recursive: true }))
        .filter(entry => entry.isFile() && !entry.name.startsWith("."))
        .map(entry => relative(dir, join(entry.parentPath, entry.name)).split(sep).join("/"))
        .sort();
      skills.push({ name, description, files });
    }
    return skills;
  }

  async readSkillFile(skill: string, file: string): Promise<string> {
    const info = (await this.getSkillDirs()).get(skill);
    if (!info)
      throw new Error(`Unknown skill '${skill}'`);
    return await readFile(join(info.dir, file), "utf8");
  }

  watch(onChange: (changedFiles: string[]) => void) {
    const pending = new Set<string>();
    let timer: NodeJS.Timeout | undefined;

    const watcher = watch(this.skillsRoot, { recursive: true, persistent: false }, (_event, filename) => {
      if (filename) {
        /* Watch events report the directory name, but we name skills after their frontmatter name. These are almost
           always identical, so this is good enough to notify subscribers of specific files */
        const parts = filename.toString().split(sep);
        if (parts.length > 1)
          pending.add(parts.join("/"));
      }
      clearTimeout(timer);
      timer = setTimeout(() => { //editors often generate multiple events per save, so debounce
        const files = [...pending];
        pending.clear();
        onChange(files);
      }, 250);
    });
    watcher.on("error", err => console.error("Skills watcher error:", err));

    return () => {
      clearTimeout(timer);
      watcher.close();
    };
  }
}

/** Skills from the webhare.dev site */
class RemoteSkillSource implements SkillSource {
  private index: SkillIndex | null = null;
  private lastError = "";

  readonly aiRoot: string;
  readonly reason: string;

  /** @param aiRoot - URL of the ai/ folder on the site, ending with a slash
      @param reason - Why the remote site is used, if not because of configuration */
  constructor(aiRoot: string, reason: string) {
    this.aiRoot = aiRoot;
    this.reason = reason;
  }

  get location() {
    return this.aiRoot;
  }

  describe() {
    return `The skills are downloaded from the webhare.dev site at ${this.aiRoot}index.json${this.reason ? ` (${this.reason})` : ""}. These are read-only published copies - they cannot be edited from here. To work on skills locally, install the webhare_dev module and enable the devkit:integrations.use_checkedout_site registry key.`;
  }

  /** (Re)load the index. Returns true if it changed */
  async refresh(): Promise<boolean> {
    try {
      const response = await fetch(this.aiRoot + "index.json", { signal: AbortSignal.timeout(30_000) });
      if (!response.ok)
        throw new Error(`HTTP ${response.status} ${response.statusText}`);
      const index = await response.json() as SkillIndex;
      if (index.version !== 1 || !Array.isArray(index.skills))
        throw new Error(`Unsupported index format (version ${index.version})`);

      const changed = JSON.stringify(index) !== JSON.stringify(this.index);
      this.index = index;
      this.lastError = "";
      return changed;
    } catch (e) {
      const error = `Failed to fetch ${this.aiRoot}index.json: ${(e as Error).message}`;
      if (error !== this.lastError) //don't flood the log while the site is unreachable
        console.error(error);
      this.lastError = error;
      return false; //keep using the last index we got
    }
  }

  async listSkills(): Promise<SkillInfo[]> {
    if (!this.index)
      await this.refresh();
    return (this.index?.skills ?? []).map(skill => ({ name: skill.name, description: skill.description, files: skill.files }));
  }

  async readSkillFile(skill: string, file: string): Promise<string> {
    const info = this.index?.skills.find(s => s.name === skill);
    if (!info)
      throw new Error(`Unknown skill '${skill}'`);
    const url = new URL(`${info.path}/${file}`, this.aiRoot).toString();
    const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
    if (!response.ok)
      throw new Error(`Failed to fetch ${url}: HTTP ${response.status} ${response.statusText}`);
    return await response.text();
  }

  watch(onChange: (changedFiles: string[]) => void) {
    //The index doesn't tell us which files changed, so we report none (subscribers won't get resource updates)
    const interval = setInterval(() => void this.refresh().then(changed => changed && onChange([])), remoteRefreshInterval);
    interval.unref();
    return () => clearInterval(interval);
  }
}

/** Get the local webhare_dev skills folder, if available */
function getLocalSkillsRoot(): string | null {
  const root = backendConfig.module["webhare_dev"]?.root;
  if (!root)
    return null;
  const skillsroot = join(root, "content/ai/skills");
  return existsSync(skillsroot) && statSync(skillsroot).isDirectory() ? skillsroot : null;
}

/** Registry keys that determine where the skills come from */
const sourceRegistryKeys = ["devkit:integrations.use_checkedout_site", "devkit:integrations.webhare_dev_site"];

/** Determine where to get the skills from, based on the devkit:integrations registry keys */
async function openSkillSource(): Promise<SkillSource> {
  const useCheckout = await readRegistryKey<boolean>("devkit:integrations.use_checkedout_site");
  let reason = "";
  if (useCheckout) {
    const localRoot = getLocalSkillsRoot();
    if (localRoot)
      return new LocalSkillSource(localRoot);
    reason = "devkit:integrations.use_checkedout_site is enabled but the webhare_dev module or its content/ai/skills folder isn't installed";
  }

  let site = await readRegistryKey<string>("devkit:integrations.webhare_dev_site") || "https://www.webhare.dev/";
  if (!site.endsWith("/"))
    site += "/";
  const source = new RemoteSkillSource(new URL("ai/", site).toString(), reason);
  await source.refresh();
  return source;
}

/** Manages the skills offered by the MCP server. Switches to another skill source when the devkit:integrations
    registry keys change */
export class SkillProvider {
  source: SkillSource;
  private onChange: ((changedUris: string[]) => void) | null = null;
  private stopWatching: (() => void) | null = null;
  /** Serializes reloads if registry change events come in quickly */
  private reloading = Promise.resolve();

  private constructor(source: SkillSource) {
    this.source = source;
  }

  /** Create a provider using the source configured in the registry, and follow registry changes */
  static async open(): Promise<SkillProvider> {
    let provider: SkillProvider | null = null;
    //subscribe before the initial read so we can't miss a change in between
    await subscribe(getRegistryKeyEventMasks(sourceRegistryKeys), () => void provider?.reload());
    provider = new SkillProvider(await openSkillSource());
    return provider;
  }

  /** Reread the registry and switch to the configured source */
  private reload() {
    this.reloading = this.reloading.then(async () => {
      const newSource = await openSkillSource();
      //registry events are per node, so this may not even concern our keys
      if (newSource.describe() === this.source.describe())
        return;

      console.error(`Skills source changed to: ${newSource.location}`);
      this.stopWatching?.();
      this.source = newSource;
      if (this.onChange) {
        this.startWatching();
        this.onChange([]);
      }
    }).catch(e => console.error("Failed to switch skills source:", e));
  }

  private startWatching() {
    const onChange = this.onChange!;
    this.stopWatching = this.source.watch(files => onChange(files.map(file => skillUriPrefix + file)));
  }

  private async getSkill(name: string) {
    return (await this.source.listSkills()).find(s => s.name === name) ?? null;
  }

  private getMimeType(path: string): string {
    if (path.endsWith(".md"))
      return "text/markdown";
    if (path.endsWith(".json"))
      return "application/json";
    if (path.endsWith(".yml") || path.endsWith(".yaml"))
      return "application/yaml";
    if (/\.(ts|js|mjs|cjs)$/.test(path))
      return "text/javascript";
    return "text/plain";
  }

  /** List all skill files as MCP resources */
  async listResources() {
    return (await this.source.listSkills()).flatMap(skill => skill.files.map(file => ({
      uri: `${skillUriPrefix}${skill.name}/${file}`,
      name: file === "SKILL.md" ? skill.name : `${skill.name}/${file}`,
      description: file === "SKILL.md" ? skill.description : `Supporting file for the '${skill.name}' skill`,
      mimeType: this.getMimeType(file)
    })));
  }

  /** Read a skill file. Returns null if the skill or file doesn't exist */
  private async readFile(skillname: string, file: string): Promise<string | null> {
    const skill = await this.getSkill(skillname);
    //only serve files we would list ourselves, which also prevents escaping the skill directory
    if (!skill?.files.includes(file))
      return null;
    return await this.source.readSkillFile(skill.name, file);
  }

  /** Read a skill resource. Returns null if the URI isn't a skill resource or doesn't exist */
  async readResource(uri: string): Promise<{ uri: string; mimeType: string; text: string } | null> {
    if (!uri.startsWith(skillUriPrefix))
      return null;

    const path = uri.slice(skillUriPrefix.length);
    const slash = path.indexOf("/");
    const text = await this.readFile(slash >= 0 ? path.slice(0, slash) : path, slash >= 0 ? path.slice(slash + 1) : "SKILL.md");
    return text === null ? null : { uri, mimeType: this.getMimeType(uri), text };
  }

  /** List skills as MCP prompts so users can explicitly invoke them */
  async listPrompts() {
    return (await this.source.listSkills()).map(skill => ({ name: skill.name, description: skill.description }));
  }

  /** Get a skill as MCP prompt. Returns null if not found */
  async getPrompt(name: string) {
    const skill = await this.getSkill(name);
    const content = skill && await this.readFile(name, "SKILL.md");
    if (!skill || content === null)
      return null;

    const { body } = parseFrontmatter(content);
    const otherfiles = skill.files.filter(file => file !== "SKILL.md");
    let text = `<skill name="${skill.name}">\n${body.trim()}\n</skill>`;
    if (otherfiles.length)
      text += `\n\nThis skill has supporting files, which can be loaded using the ${skillToolName} tool (with file set) or as MCP resources:\n${otherfiles.map(file => `- ${file}: ${skillUriPrefix}${skill.name}/${file}`).join("\n")}`;

    return {
      description: skill.description,
      messages: [{ role: "user" as const, content: { type: "text" as const, text } }]
    };
  }

  /* Why skills are advertised through the wh_get_skill tool (SPECULATIVE - UNPROVEN)

     MCP has no native 'skills' primitive. For a skill to be useful, the model needs its name and description in its
     context so it knows when to load it. We considered these channels:
     - Server `instructions`: clients such as Claude Code inject these into the system prompt, but they are only sent
       once in the `initialize` response. MCP has no notification to refresh them, so skills added or changed while a
       session is running would stay invisible until the client reconnects.
     - Resources and prompts: these have list_changed notifications, but resource lists generally aren't in the model's
       context (the model has to explicitly ask for them) and prompts are user-invoked slash commands, not something the
       model discovers by itself.
     - Tool descriptions: these are in the model's context AND have a `notifications/tools/list_changed` notification.

     So we put the skill list into the description of the wh_get_skill tool and send tools/list_changed when the skills
     change. This is speculative: we have verified that the server sends the notification and returns an updated
     tool list, but NOT that clients (eg Claude Code) actually refresh the tool definitions in the model's context mid-session
     after receiving it. If they don't, this approach is no better than listing the skills in the server instructions.
     It also costs context: the full skill list is part of the tool definitions in every request. To verify: start a
     session, add a skill to the skills folder, and ask the model which WebHare skills it knows about.
  */

  /** Server instructions pointing to the skill tool. The skill list and where the skills come from (which can change
      when the registry keys change) live in the tool description, as clients can refresh that (see above - unproven) */
  getInstructions(): string {
    return `This server offers WebHare development skills. The description of the ${skillToolName} tool lists the available skills and where they come from. Before working on a task that matches one of these skills, use ${skillToolName} to load its instructions.`;
  }

  /** Get the definition of the skill tool, listing all current skills. Returns null if there are no skills */
  async getTool() {
    const skills = await this.source.listSkills();
    if (!skills.length)
      return null;

    return {
      name: skillToolName,
      description: `Load a WebHare development skill. Before working on a task that matches one of the skills below, load it with this tool and follow its instructions.\n\nAvailable skills:\n`
        + skills.map(skill => `- ${skill.name}: ${skill.description}`).join("\n")
        + `\n\n${this.source.describe()}`,
      inputSchema: {
        type: "object" as const,
        properties: {
          name: {
            type: "string",
            enum: skills.map(skill => skill.name),
            description: "Name of the skill to load"
          },
          file: {
            type: "string",
            description: "Supporting file of the skill to load, as referenced by the skill. Defaults to SKILL.md"
          }
        },
        required: ["name"]
      }
    };
  }

  /** Execute the skill tool. Returns null if the skill or file doesn't exist */
  async runTool(name: string, file?: string): Promise<string | null> {
    if (!file || file === "SKILL.md")
      return (await this.getPrompt(name))?.messages[0].content.text ?? null;
    return await this.readFile(name, file);
  }

  /** Watch for skill changes (including switching to another source). Invokes the callback with the resource URIs of
      changed files, if known */
  watch(onChange: (changedUris: string[]) => void) {
    this.onChange = onChange;
    this.startWatching();
  }
}

export const skillToolName = "wh_get_skill";
