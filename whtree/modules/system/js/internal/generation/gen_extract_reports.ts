import { resolveResource } from "@webhare/services";
import type { ModuleQualifiedName } from "@webhare/services/src/naming";
import type { GenerateContext } from "./shared";

/** Supported report output formats. 'application/x-webhare-spreadsheet' means onGenerate returns SpreadsheetData/WorkbookData from \@webhare/office-formats */
export type ReportOutputFormat = "application/x-webhare-spreadsheet";

export type ReportDescriptor = {
  /** Fully qualified name, eg publisher:seosettings */
  name: ModuleQualifiedName;
  /** Resolved Tollium screen to configure the report (eg mod::module/screens/reports.xml#config). Empty if not set */
  configScreen: string;
  /** Resolved function that generates the report (eg mod::module/js/reports.ts#generateReport) */
  onGenerate: string;
  /** Output format generated by onGenerate */
  outputFormat: ReportOutputFormat;
};

export type ReportsExtract = {
  reports: ReportDescriptor[];
};

export async function generateReports(context: GenerateContext): Promise<string> {
  const retval: ReportsExtract = {
    reports: []
  };

  for (const mod of context.moduledefs)
    for (const [name, report] of Object.entries(mod.modYml?.reports || {})) {
      retval.reports.push({
        name: `${mod.name}:${name}`,
        configScreen: report.configScreen ? resolveResource(mod.resourceBase, report.configScreen) : "",
        onGenerate: resolveResource(mod.resourceBase, report.onGenerate),
        outputFormat: report.outputFormat
      });
    }

  return JSON.stringify(retval, null, 2) + "\n";
}
